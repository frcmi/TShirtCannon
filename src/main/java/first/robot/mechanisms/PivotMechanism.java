/**
 * An arm driven by a Kraken X60 through a TalonFX. Generated by YAMG.
 *
 * <p>Angles are measured from horizontal: 0 degrees points the arm straight out, and positive
 * angles raise it.
 */
public class PivotMechanism implements Mechanism {

  private static final int CAN_ID = 1;
  private static final DCMotor DC_MOTOR = DCMotor.getKrakenX60(1);
  /** Motor rotations per arm rotation. */
  private static final double GEAR_RATIO = 12.0;
  private static final boolean BRAKE_MODE = true;
  private static final Current STATOR_CURRENT_LIMIT = Amps.of(40.0);
  /** How often the robot loop runs. */
  private static final Time LOOP_PERIOD = Seconds.of(0.020);

  // Closed loop gains, in volts per rotation of error.
  private static final double KP = 10.0;
  private static final double KI = 0.0;
  private static final double KD = 1.0;
  private static final double KG = 0.23;

  // The arm's size, its physical limits, and where it is when the robot turns on.
  private static final Angle MIN_ANGLE = Degrees.of(0.0);
  private static final Angle MAX_ANGLE = Degrees.of(90.0);
  private static final Angle STARTING_ANGLE = Degrees.of(0.0);
  private static final Angle STARTING_MECHANISM_POSITION = STARTING_ANGLE;

  // The Talon FX, and the requests that control it.
  private final TalonFX motor = new TalonFX(CAN_ID, new CANBus(CANPort.CAN_S0));
  // PositionVoltage: the Talon's closed loop goes straight to the goal.
  private final PositionVoltage positionRequest = new PositionVoltage(0);
  private final VoltageOut voltageRequest = new VoltageOut(0);
  // The CTRE CANcoder with CAN ID 20 on CAN bus CAN_S0, which knows where the arm is when
  // the robot turns on.
  // What it reads with the arm at zero.
  private static final Angle ABSOLUTE_ENCODER_OFFSET = Degrees.of(0.0);
  /** Encoder rotations per arm rotation. */
  private static final double ABSOLUTE_ENCODER_RATIO = 1.0;
  /** The middle of the travel between the hard stops. The encoder's reading is taken within half an encoder turn of it. */
  private static final Angle ABSOLUTE_TRAVEL_MIDDLE = Degrees.of(45.0);
  // A CTRE CANcoder with CAN ID 20 on CAN bus CAN_S0.
  private final CANcoder cancoder = new CANcoder(
    20,
    new CANBus(CANPort.CAN_S0)
  );

  // Where the closed loop is going. Null means the closed loop is off.
  private Angle goal = null;

  // The simulated speed last loop, to work out the acceleration.
  private AngularVelocity lastMechanismVelocity = RotationsPerSecond.of(0);

  public PivotMechanism() {
    TalonFXConfiguration config = new TalonFXConfiguration();
    // Phoenix applies the gearing, so positions, speeds, soft limits and gains are all in turns of
    // the mechanism, and its closed loop outputs volts.
    config.Feedback.withSensorToMechanismRatio(GEAR_RATIO);
    config.Slot0.withKP(KP).withKI(KI).withKD(KD);
    // The Talon runs the feedforward itself, with its gains per turn of the mechanism.
    // Arm_Cosine scales kG by the cosine of the arm's angle, which is 0 when the arm points straight out.
    // kV and kA are per turn already.
    config.Slot0.withGravityType(GravityTypeValue.Arm_Cosine).withKG(KG);
    config.Slot0.withKS(0.0).withKV(0.0).withKA(0.0);
    config.MotorOutput.withNeutralMode(
      BRAKE_MODE ? NeutralModeValue.Brake : NeutralModeValue.Coast
    );
    config.CurrentLimits.withStatorCurrentLimit(
      STATOR_CURRENT_LIMIT
    ).withStatorCurrentLimitEnable(true);
    motor.getConfigurator().apply(config);
    if (RobotBase.isSimulation()) {
      // Simulate the motor the Talon FX really drives.
      motor.getSimState().setMotorType(TalonFXSimState.MotorType.KrakenX60);
      // Start the simulated rotor where the mechanism starts, so that the Talon's position does
      // not count the starting position twice.
      motor
        .getSimState()
        .setRawRotorPosition(STARTING_MECHANISM_POSITION.times(GEAR_RATIO));
    }
    motor.setPosition(STARTING_MECHANISM_POSITION);
    if (RobotBase.isReal()) {
      // Start the motor's encoder where the absolute encoder says the arm is.
      // Simulation has no encoder, so there it starts at its starting position.
      setEncoderPosition(
        getAbsoluteAngle(
          cancoder.getAbsolutePosition().waitForUpdate(0.25).getValue()
        )
      );
    }
    if (RobotBase.isSimulation()) {}
  }

  /**
   * Where the absolute encoder says the arm is. The encoder only knows where it is
   * within one of its own turns, so this is the angle within half an encoder turn of the middle of
   * the travel.
   */
  private Angle getAbsoluteAngle(Angle reading) {
    // How far the encoder has turned from where it reads with the arm at zero.
    Angle fromZero = reading.minus(ABSOLUTE_ENCODER_OFFSET);
    // How far that is from the middle of the travel, as an encoder angle from -0.5 to 0.5 rotations.
    double fromMiddle = MathUtil.inputModulus(
      fromZero
        .minus(ABSOLUTE_TRAVEL_MIDDLE.times(ABSOLUTE_ENCODER_RATIO))
        .in(Rotations),
      -0.5,
      0.5
    );
    return ABSOLUTE_TRAVEL_MIDDLE.plus(
      Rotations.of(fromMiddle).div(ABSOLUTE_ENCODER_RATIO)
    );
  }

  /**
   * What the absolute encoder reads, before the offset and inversion. Move the arm to
   * zero, and this is the offset.
   */
  public Angle getAbsoluteEncoderReading() {
    return cancoder.getAbsolutePosition().refresh().getValue();
  }

  /**
   * Where the absolute encoder says the arm is. It should follow the arm's
   * angle. If it goes the opposite way, the encoder needs inverting.
   */
  public Angle getAbsoluteEncoderAngle() {
    return getAbsoluteAngle(getAbsoluteEncoderReading());
  }

  /** Set the motor's encoder to a arm angle. */
  private void setEncoderPosition(Angle mechanismPosition) {
    motor.setPosition(mechanismPosition);
  }

  private Angle getMechanismPosition() {
    return motor.getPosition().getValue();
  }

  private AngularVelocity getMechanismVelocity() {
    return motor.getVelocity().getValue();
  }

  /** The arm's angle, from horizontal. */
  public Angle getAngle() {
    return getMechanismPosition();
  }

  /** How fast the arm is turning. */
  public AngularVelocity getVelocity() {
    return getMechanismVelocity();
  }

  /** The voltage the motor controller is applying to the motor. */
  public Voltage getVoltage() {
    return motor.getMotorVoltage().getValue();
  }

  /** The motor's stator current. */
  public Current getCurrent() {
    return motor.getStatorCurrent().getValue();
  }

  /** The motor's temperature. */
  public Temperature getTemperature() {
    return motor.getDeviceTemp().getValue();
  }

  /** Send the motor controller the goal. It runs the closed loop and the feedforward itself. */
  private void setMechanismGoal(Angle goal) {
    motor.setControl(positionRequest.withPosition(goal));
  }

  private void setMotorVoltage(Voltage voltage) {
    motor.setControl(voltageRequest.withOutput(voltage));
  }

  /** Start moving the arm to an angle with the closed loop. */
  private void setGoal(Angle angle) {
    Angle clamped = angle.lt(MIN_ANGLE)
      ? MIN_ANGLE
      : angle.gt(MAX_ANGLE) ? MAX_ANGLE : angle;
    if (goal == null || !clamped.isEquivalent(goal)) {
      // The Talon runs the closed loop itself, so it only needs the goal when it changes.
      setMechanismGoal(clamped);
    }
    goal = clamped;
  }

  /** The angle the closed loop is moving the arm to, or empty while the closed loop is off. */
  public Optional<Angle> getGoal() {
    return Optional.ofNullable(goal);
  }

  /** Go to an angle and hold it. This command does not end on its own. */
  public Command setAngle(Angle angle) {
    return run(coroutine -> {
      while (true) {
        setGoal(angle);
        coroutine.yield();
      }
    }).named("ArmMechanism Set Angle");
  }

  /** Drive the arm with a duty cycle from -1 to 1. The closed loop is not used. */
  public Command set(double dutyCycle) {
    return run(coroutine -> {
      goal = null;
      while (true) {
        setMotorVoltage(
          RobotController.getMeasureBatteryVoltage().times(dutyCycle)
        );
        coroutine.yield();
      }
    }).named("ArmMechanism Set Duty Cycle");
  }

  /** True while the arm is within a tolerance of an angle. */
  public Trigger near(Angle angle, Angle tolerance) {
    return new Trigger(() -> getAngle().isNear(angle, tolerance));
  }

  /** Hold an angle at the lowest priority, so that any other command for this mechanism can interrupt it. */
  public Command hold(Angle angle) {
    return run(coroutine -> {
      while (true) {
        setGoal(angle);
        coroutine.yield();
      }
    })
      .withPriority(Command.LOWEST_PRIORITY)
      .named("ArmMechanism Hold");
  }

  /** Call this from Robot.robotPeriodic(), before the scheduler runs. */
  public void periodic() {
    // The goal is published only while the closed loop has one, as YAMS's telemetry does.
    if (goal != null) {
      Telemetry.log("PivotSubsystem/Goal", goal);
    }
    Telemetry.log("PivotSubsystem/Angle", getAngle());
    Telemetry.log("PivotSubsystem/Velocity", getVelocity());
    Telemetry.log("PivotSubsystem/Voltage", getVoltage());
    // The encoder's reading sets its offset, and its angle shows whether it needs inverting.
    Telemetry.log(
      "PivotSubsystem/AbsoluteEncoder/Reading",
      getAbsoluteEncoderReading()
    );
    Telemetry.log(
      "PivotSubsystem/AbsoluteEncoder/Angle",
      getAbsoluteEncoderAngle()
    );
  }

  /** Call this from Robot.simulationPeriodic(). */
  public void simulationPeriodic() {
  }
}